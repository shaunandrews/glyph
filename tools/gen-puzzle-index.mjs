// Writes server/puzzles/index.ts: every day file imported statically (Zero rejects dynamic import()).
import { readdirSync, writeFileSync } from "node:fs";
const dir = new URL("../server/puzzles/days/", import.meta.url);
const days = readdirSync(dir).filter((f) => /^\d{4}-\d{2}-\d{2}\.ts$/.test(f)).sort();
const name = (f) => "d" + f.slice(0, 10).replace(/-/g, "");
const out = `// Generated by tools/gen-puzzle-index.mjs. Don't edit.
import type { Day } from "../../shared/types";
${days.map((f) => `import ${name(f)} from "./days/${f.slice(0, -3)}";`).join("\n")}

export const DAYS: Record<string, Day> = {
${days.map((f) => `  "${f.slice(0, 10)}": ${name(f)},`).join("\n")}
};
`;
writeFileSync(new URL("../server/puzzles/index.ts", import.meta.url), out);
console.log(`puzzles/index.ts: ${days.length} days`);
